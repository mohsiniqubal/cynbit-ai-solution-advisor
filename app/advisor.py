"""Explainable baseline matching for the Cynbit AI Solution Advisor."""
from __future__ import annotations
from typing import Iterable
from sklearn.feature_extraction.text import TfidfVectorizer
from sklearn.metrics.pairwise import cosine_similarity
from app.catalogue import CATALOGUE

def _text(item: dict) -> str:
    return " ".join([item["name"], item["category"], item["description"], item["fit"]])

def recommend(problem: str, sector: str = "", goals: str = "", constraints: str = "", top_k: int = 3) -> list[dict]:
    """Rank catalogue entries by TF-IDF cosine similarity; scores are not probabilities."""
    query = " ".join(x.strip() for x in [problem, sector, goals, constraints] if x and x.strip()).strip()
    if not query:
        return []
    docs = [_text(item) for item in CATALOGUE]
    vectorizer = TfidfVectorizer(stop_words="english", ngram_range=(1, 2), sublinear_tf=True)
    matrix = vectorizer.fit_transform(docs + [query])
    scores = cosine_similarity(matrix[-1], matrix[:-1]).ravel()
    query_terms = set(vectorizer.build_analyzer()(query))
    results = []
    for idx in scores.argsort()[::-1][:max(1, min(top_k, len(CATALOGUE)))]:
        item = dict(CATALOGUE[int(idx)])
        catalogue_terms = set(vectorizer.build_analyzer()(_text(item)))
        matched = sorted(query_terms & catalogue_terms)
        item["score"] = round(float(scores[idx]), 3)
        item["matched_terms"] = matched[:10]
        item["score_note"] = "Text similarity only — not a probability or guarantee of fit."
        results.append(item)
    return results

def create_brief(name: str, sector: str, problem: str, goals: str, constraints: str,
                 timeline: str, recommendations: Iterable[dict]) -> str:
    recs = list(recommendations)
    lines = [
        "# Cynbit — Discovery Brief", "",
        "> Draft generated by a prototype advisor. Validate all recommendations with a human before sharing externally.", "",
        "## Prospect context", f"- Organization / contact: {name.strip() or 'Not provided'}",
        f"- Sector: {sector.strip() or 'Not provided'}",
        f"- Desired timeline: {timeline.strip() or 'Not provided'}", "",
        "## Business challenge", problem.strip() or "Not provided", "",
        "## Desired outcomes", goals.strip() or "Not provided", "",
        "## Constraints / current environment", constraints.strip() or "Not provided", "",
        "## Suggested areas to explore", ""
    ]
    if not recs:
        lines.append("No recommendations generated. Add a more specific business challenge and try again.")
    for i, rec in enumerate(recs, 1):
        lines.extend([
            f"### {i}. {rec['name']}", f"- Category: {rec['category']}",
            f"- Similarity score: {rec['score']:.3f} (not a probability)",
            f"- Why it may fit: {rec['fit']}",
            f"- Matched terms: {', '.join(rec.get('matched_terms', [])) or 'No clear shared terms'}",
            "- Discovery questions:"
        ])
        lines.extend([f"  - {q}" for q in rec["discovery_questions"]])
        lines.append("")
    lines.extend([
        "## Recommended next step", "Run a short discovery call, confirm the problem and baseline metrics, validate data/security constraints, and agree on a measurable pilot before estimating ROI.", "",
        "## Human review checklist", "- Confirm the recommendation and service scope.",
        "- Validate any claims, timeline, security, and integration assumptions.",
        "- Do not send this draft to a prospect without review.", ""
    ])
    return "\n".join(lines)
